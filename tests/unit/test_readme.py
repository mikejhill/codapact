def test_coda_without_a_published_api_has_no_source_section_or_badges() -> None:
    settings = ReadmeSettings(
        about="A command-line tool for making calls to Acme.",
        source_type="openapi",
        location="acme.yaml",
        contract="acme.yaml",
        contract_path="acme.yaml",
        sha256="cd" * 32,
    )
    info = Package("codapact_acme", "codapact-acme", "codapact-acme", None)
    text = render_readme(Api("Acme", "", ()), info, settings, "1.0.0")
    assert text.startswith(
        "# codapact-acme\n\nA command-line tool for making calls to Acme.\n\n## Run"
    )
    assert "## API source" not in text and "[![" not in text and "sync" not in text
    assert "from this directory (the package is not published)" in text
    assert "uvx --from . codapact-acme --help" in text and "--refresh-package" not in text
    assert "## Credentials" not in text
    assert "\nuv run pytest" in text and "CODAPACT_ACME_E2E_LIVE=1" in text


