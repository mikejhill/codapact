def test_remote_contract_has_no_local_link(tmp_path: Path) -> None:
    config = ProjectConfig.from_data(
        {
            "version": 1,
            "source": {"type": "openapi", "path": "https://p.example/openapi.yaml"},
            "readme": {"docs": "https://p.example"},
            "targets": [{"name": "python", "output": "out"}],
        },
        base=tmp_path,
    )
    result = Pipeline(default_registry(), _PetstoreFetcher()).run(config, dry_run=True)
    files = {f.path: f.content for f in result.outputs[tmp_path / "out"]}
    assert "OpenAPI at <https://p.example/openapi.yaml>" in files["README.md"]


class _PetstoreFetcher(Fetcher):
    """Serve the petstore example for any location."""

    @override
    def fetch(
        self, location: str, *, base: Path | None = None, max_bytes: int | None = None
    ) -> SourceDocument:
        return super().fetch(str(EXAMPLES / "petstore" / "openapi.yaml"))


@pytest.mark.parametrize(
    ("readme", "message"),
    [
        ([], "readme must be a mapping"),
        ({"title": "x"}, "unknown keys"),
        ({"name": " "}, "readme.name must be a non-empty string"),
        ({"about": 3}, "readme.about must be a non-empty string"),
        ({"docs": "ftp://x"}, "readme.docs must be an http"),
        ({"repository": "not a repo"}, "readme.repository must be a GitHub repository"),
        ({"repository": 5}, "readme.repository must be a GitHub repository"),
        ({"pypi": "yes"}, "readme.pypi must be true or false"),
        ({"badges": ["stars"]}, "readme.badges must be a list"),
        ({"badges": "ci"}, "readme.badges must be a list"),
        ({"examples": [""]}, "readme.examples must be a list"),
        ({"examples": "x"}, "readme.examples must be a list"),
        ({"sections": [{"title": "T"}]}, "readme.sections must be a list"),
        ({"sections": [{"title": "T", "body": ""}]}, "readme.sections must be a list"),
        ({"sections": "x"}, "readme.sections must be a list"),
    ],
)
def test_readme_config_is_validated(readme: Any, message: str) -> None:
    data = {
        "version": 1,
        "source": {"type": "openapi", "path": "x.yaml"},
        "readme": readme,
        "targets": [{"name": "python", "output": "out"}],
    }
    with pytest.raises(ConfigError, match=message):
        ProjectConfig.from_data(data, base=Path())


def test_readme_repository_is_normalized() -> None:
    data = {
        "version": 1,
        "source": {"type": "openapi", "path": "x.yaml"},
        "readme": {"repository": "https://github.com/acme/cli/", "pypi": False},
        "targets": [{"name": "python", "output": "out"}],
    }
    assert ProjectConfig.from_data(data, base=Path()).readme == {
        "repository": "acme/cli",
        "pypi": False,
    }
