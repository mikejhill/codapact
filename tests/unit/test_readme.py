def test_uvx_tool_names_the_distribution_when_the_command_differs() -> None:
    info = Package("acme", "acme-api", "acme")
    assert tool(info, ReadmeSettings(pypi=True)) == "--from acme-api acme"
    assert tool(info, ReadmeSettings(package_dir="gen/python")) == "--from ./gen/python acme"
    assert tool(info, ReadmeSettings(package_dir="../pkg")) == "--from ../pkg acme"
    assert tool(Package("acme", "acme"), ReadmeSettings(pypi=True)) == "acme"


def test_settings_from_options_defaults_pypi_to_having_a_repository() -> None:
    assert ReadmeSettings.from_options({}) == ReadmeSettings()
    hosted = ReadmeSettings.from_options(
        {"readme": {"settings": {"repository": "a/b", "sections": [{"title": "T", "body": "B"}]}}}
    )
    assert hosted.pypi and hosted.sections == (("T", "B"),)


def test_python_readme_target_needs_a_package() -> None:
    api = Api("X", "1", ())
    request = GenerationRequest(api, derive_surface(api), None, {})
    with pytest.raises(PluginError, match="needs a python target"):
        PythonReadmeTarget(CAPABILITIES).generate(request)


def _config(tmp_path: Path, readme: dict[str, Any], **source: Any) -> ProjectConfig:
    contract = tmp_path / "openapi.yaml"
    contract.write_bytes((EXAMPLES / "petstore" / "openapi.yaml").read_bytes())
    return ProjectConfig.from_data(
        {
            "version": 1,
            "source": {"type": "openapi", "path": "openapi.yaml", **source},
            "cli": {"env_prefix": "PETS", "auth": {"token": {"docs": "Ask the shop."}}},
            "readme": readme,
            "targets": [
                {
                    "name": "python",
                    "output": "gen/python",
                    "options": {"package": "codapact_pets", "distribution": "codapact-pets"},
                },
                {"name": "python-cli", "output": "gen/python"},
                {"name": "python-readme", "output": "."},
            ],
        },
        base=tmp_path,
    )


def test_pipeline_writes_the_same_format_at_the_root_and_next_to_the_package(
    tmp_path: Path,
) -> None:
    config = _config(
        tmp_path,
        {"repository": "https://github.com/acme/codapact-pets.git", "docs": "https://p.example"},
        upstream="https://p.example/openapi.yaml",
    )
    result = Pipeline(default_registry()).run(config)
    assert not result.diagnostics.has_errors, [str(d) for d in result.diagnostics]
    root = (tmp_path / "README.md").read_text()
    package = (tmp_path / "gen" / "python" / "README.md").read_text()
    for text in (root, package):
        assert text.startswith("# codapact-pets\n\n[![CI](https://github.com/acme/codapact-pets/")
        assert "blob/HEAD/openapi.yaml" in text and "uvx codapact-pets --help" in text
        assert "`PETS_TOKEN`. Ask the shop." in text
    assert "uv run --directory gen/python pytest" in root
    assert "\nuv run pytest" in package


