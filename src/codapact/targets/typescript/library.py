"""TypeScript library target.

Proves the surface is language-neutral: same model, same surface, different
idioms. Record keys use wire names (the common TypeScript SDK convention), so
the bundled runtime needs no codec; method parameters are a single camelCase
object.
"""

from __future__ import annotations

import json
import re
from importlib.resources import files
from typing import Any

from codapact.core.errors import expect
from codapact.core.naming import Name
from codapact.model.api import (
    Api,
    CursorPagination,
    GraphQLBinding,
    HttpBinding,
    OffsetPagination,
    Operation,
)
from codapact.model.types import (
    Enum,
    ListOf,
    MapOf,
    Nullable,
    Primitive,
    Record,
    Ref,
    ScalarKind,
    TypeDef,
    TypeExpr,
    Union,
)
from codapact.plugins.protocol import GeneratedFile, GenerationRequest, GenerationResponse
from codapact.surface.model import Method, Namespace

RESERVED = frozenset(
    "break case catch class const continue debugger default delete do else enum export extends "
    "false finally for function if import in instanceof new null return super switch this throw "
    "true try typeof var void while with yield let static implements interface package private "
    "protected public await".split()
)
SCALARS = {
    ScalarKind.STRING: "string",
    ScalarKind.INTEGER: "number",
    ScalarKind.FLOAT: "number",
    ScalarKind.BOOLEAN: "boolean",
    ScalarKind.BYTES: "string",
    ScalarKind.DATE: "string",
    ScalarKind.DATETIME: "string",
    ScalarKind.ANY: "unknown",
}
IDENTIFIER = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*\Z")


class TypeScriptLibraryTarget:
    """Emit an ES module package with types, a client, and the fetch runtime."""

    name = "typescript"
    capabilities = frozenset(
        {
            "binding:http",
            "binding:graphql",
            "pagination:cursor",
            "pagination:offset",
            "auth:bearer",
            "auth:basic",
            "auth:api_key",
            "auth:oauth2",
            "type:union",
            "type:map",
            "type:literal",
        }
    )
    needs_commands = False

    def generate(self, request: GenerationRequest) -> GenerationResponse:
        """Render the package."""
        api = request.api
        package = str(request.options.get("package") or Name.parse(api.name).kebab)
        runtime = files("codapact.targets.typescript").joinpath("runtime.ts").read_text("utf-8")
        output = (
            GeneratedFile("src/runtime.ts", runtime),
            GeneratedFile("src/types.ts", render_types(api)),
            GeneratedFile("src/operations.ts", render_operations(api)),
            GeneratedFile("src/client.ts", render_client(api, request.surface.root)),
            GeneratedFile("src/index.ts", _index()),
            GeneratedFile("package.json", _package_json(package, request.options)),
            GeneratedFile("tsconfig.json", _tsconfig()),
            GeneratedFile("README.md", f"# {package}\n\nGenerated by Codapact. Do not edit.\n"),
        )
        return GenerationResponse(output)


def _ident(name: Name) -> str:
    text = name.camel
    if text[0].isdigit():
        text = "n" + name.pascal
    return f"{text}_" if text in RESERVED else text


def _key(text: str) -> str:
    return text if IDENTIFIER.match(text) else json.dumps(text)


def ts_type(expr: TypeExpr, prefix: str = "") -> str:
    """Render a type expression; ``prefix`` qualifies references (``T.``)."""
    if isinstance(expr, Primitive):
        return SCALARS[expr.scalar]
    if isinstance(expr, Ref):
        return prefix + expr.name
    if isinstance(expr, ListOf):
        return f"Array<{ts_type(expr.item, prefix)}>"
    if isinstance(expr, MapOf):
        return f"Record<string, {ts_type(expr.value, prefix)}>"
    if isinstance(expr, Nullable):
        return f"{ts_type(expr.inner, prefix)} | null"
    return json.dumps(expr.value)


def _comment(text: str, indent: str = "") -> str:
    text = text.strip().replace("*/", "*\\/")
    if not text:
        return ""
    lines = text.splitlines()
    return indent + "/**\n" + "".join(f"{indent} * {line}\n" for line in lines) + indent + " */\n"


def render_types(api: Api) -> str:
    """Render ``types.ts``."""
    out = ["// Types generated from the semantic model. Do not edit.\n"]
    for definition in api.types:
        out.append(_comment(definition.docs) + _definition(definition))
    return "\n".join(out)


def _definition(definition: TypeDef) -> str:
    name = definition.name
    if isinstance(definition, Record):
        lines = [f"export type {name} = {{"]
        for f in definition.fields:
            optional = "" if f.required else "?"
            lines.append(_comment(f.docs, "  ") + f"  {_key(f.wire)}{optional}: {ts_type(f.type)};")
        if definition.additional is not None:
            lines.append("  [key: string]: unknown;")
        lines.append("};\n")
        return "\n".join(lines)
    if isinstance(definition, Enum):
        values = " | ".join(json.dumps(v.value) for v in definition.values)
        return f"export type {name} = {values};\n"
    if isinstance(definition, Union):
        return f"export type {name} = {' | '.join(ts_type(v.type) for v in definition.variants)};\n"
    return f"export type {name} = {ts_type(definition.target)};\n"


def _operation_spec(api: Api, operation: Operation) -> dict[str, Any]:
    spec: dict[str, Any] = {
        "name": operation.name,
        "auth": [list(a) for a in operation.auth.alternatives],
        "idempotent": operation.idempotent,
    }
    paging = operation.pagination
    if isinstance(paging, CursorPagination):
        spec["paging"] = {
            "style": "cursor",
            "param": paging.cursor_param,
            "items": _wire_path(api, operation.result, paging.items),
            "next": _wire_path(api, operation.result, paging.next_cursor),
        }
    elif isinstance(paging, OffsetPagination):
        spec["paging"] = {
            "style": "offset",
            "param": paging.offset_param,
            "items": _wire_path(api, operation.result, paging.items),
        }
    http = operation.binding(HttpBinding)
    if http is not None:
        spec.update(
            kind="http",
            method=http.method,
            path=http.path,
            params=[[p.param, p.location.value, p.wire_name, p.explode] for p in http.params],
            responses=[[r.status, r.outcome, r.media_type] for r in http.responses],
            requestMediaType=http.request_media_type,
        )
        return spec
    graphql = expect(operation.binding(GraphQLBinding), "GraphQL binding")
    spec.update(
        kind="graphql",
        document=graphql.document,
        operationName=graphql.operation_name,
        variables=[list(v) for v in graphql.variables],
        unwrap=graphql.unwrap,
    )
    return spec


def _wire_path(api: Api, expr: TypeExpr | None, path: tuple[str, ...]) -> list[str]:
    """Translate a field-name path into wire names, since TS data keeps wire keys."""
    result = []
    current = expr
    for part in path:
        while isinstance(current, Nullable):
            current = current.inner
        definition = api.type(current.name) if isinstance(current, Ref) else None
        field = (
            next((f for f in definition.fields if f.name == part), None)
            if isinstance(definition, Record)
            else None
        )
        result.append(field.wire if field else part)
        current = field.type if field else None
    return result


def render_operations(api: Api) -> str:
    """Render ``operations.ts``: binding tables consumed by the runtime."""
    operations = {op.name: _operation_spec(api, op) for op in api.operations}
    schemes = {
        s.name: {
            "kind": s.kind.value,
            **({"location": s.location.value} if s.location else {}),
            **({"wire": s.wire_name} if s.wire_name else {}),
        }
        for s in api.auth_schemes
    }
    default = api.servers[0].url if api.servers else None
    return (
        "// Protocol bindings generated from the semantic model. Do not edit.\n"
        'import type { OperationSpec, SchemeSpec } from "./runtime.ts";\n\n'
        f"export const DEFAULT_BASE_URL: string | null = {json.dumps(default)};\n\n"
        f"export const SCHEMES: Record<string, SchemeSpec> = {json.dumps(schemes, indent=2)};\n\n"
        "export const OPERATIONS = "
        + json.dumps(operations, indent=2)
        + " satisfies Record<string, OperationSpec>;\n"
    )


def render_client(api: Api, root: Namespace) -> str:
    """Render ``client.ts``."""
    out = [
        "// Client generated from the library surface. Do not edit.",
        'import { Runtime, type ClientOptions } from "./runtime.ts";',
        'import { DEFAULT_BASE_URL, OPERATIONS, SCHEMES } from "./operations.ts";',
        'import type * as T from "./types.ts";\n',
    ]
    classes: list[str] = []
    _namespace_class(api, root, (), classes)
    out.extend(classes)
    return "\n".join(out)


def _class_name(path: tuple[Name, ...]) -> str:
    return "".join(n.pascal for n in path) + "Resource" if path else "Client"


def _namespace_class(
    api: Api, namespace: Namespace, path: tuple[Name, ...], out: list[str]
) -> None:
    here = path + ((namespace.name,) if namespace.name is not None else ())
    for child in namespace.children:
        _namespace_class(api, child, here, out)
    lines = [f"export class {_class_name(here)} {{"]
    for child in namespace.children:
        lines.append(f"  readonly {_ident(child.label)}: {_class_name(here + (child.label,))};")
    lines.append("  private readonly runtime: Runtime;")
    if here:
        lines.append("  constructor(runtime: Runtime) {")
        lines.append("    this.runtime = runtime;")
    else:
        lines.append("  constructor(options: ClientOptions = {}) {")
        lines.append("    this.runtime = new Runtime(options, SCHEMES, DEFAULT_BASE_URL);")
    for child in namespace.children:
        resource = _class_name(here + (child.label,))
        lines.append(f"    this.{_ident(child.label)} = new {resource}(this.runtime);")
    lines.append("  }")
    for method in namespace.methods:
        lines.append(_method(api, method))
    lines.append("}\n")
    out.append("\n".join(lines))


def _qualified(expr: TypeExpr) -> str:
    return ts_type(expr, "T.")


def _method(api: Api, method: Method) -> str:
    name = _ident(method.name)
    fields = []
    for param in method.params:
        optional = "" if param.required else "?"
        fields.append(f"{_ident(param.name)}{optional}: {_qualified(param.type)}")
    has_required = any(p.required for p in method.params)
    params_type = "{ " + "; ".join(fields) + " }" if fields else "Record<string, never>"
    default = "" if has_required else " = {}"
    returns = _qualified(method.returns) if method.returns is not None else "void"
    flat = []
    nested: dict[str, list[str]] = {}
    for param in method.params:
        value = f"params.{_ident(param.name)}"
        if param.source.field is None:
            flat.append(f"{json.dumps(param.source.param)}: {value}")
        else:
            wire = _field_wire(api, method, param.source.param, param.source.field)
            nested.setdefault(param.source.param, []).append(f"{json.dumps(wire)}: {value}")
    for source, items in nested.items():
        flat.append(f"{json.dumps(source)}: {{ {', '.join(items)} }}")
    args = "{ " + ", ".join(flat) + " }" if flat else "{}"
    op = f"OPERATIONS[{json.dumps(method.operation)}]"
    doc = _comment(method.summary or method.docs, "  ")
    lines = [
        doc + f"  async {name}(params: {params_type}{default}): Promise<{returns}> {{",
        f"    return (await this.runtime.call({op}, {args})) as {returns};",
        "  }",
    ]
    if method.paging is not None:
        item = _qualified(method.paging.item)
        lines += [
            f"  async *{name}Iter(params: {params_type}{default}, maxItems?: number): "
            f"AsyncGenerator<{item}> {{",
            f"    yield* this.runtime.paginate({op}, {args}, maxItems) as AsyncGenerator<{item}>;",
            "  }",
        ]
    return "\n".join(lines)


def _field_wire(api: Api, method: Method, param: str, field: str) -> str:
    operation = api.operation(method.operation)
    expr = next(p.type for p in operation.params if p.name == param)
    definition = api.type(expr.name) if isinstance(expr, Ref) else None
    if isinstance(definition, Record):
        for f in definition.fields:
            if f.name == field:
                return f.wire
    return field


def _index() -> str:
    return (
        'export { Client } from "./client.ts";\n'
        "export { ApiError, AuthError, GraphQLResponseError, type ClientOptions } "
        'from "./runtime.ts";\n'
        'export type * from "./types.ts";\n'
    )


def _package_json(package: str, options: Any) -> str:
    data = {
        "name": package,
        "version": str(options.get("version") or "0.1.0"),
        "type": "module",
        "main": "src/index.ts",
        "types": "src/index.ts",
        "scripts": {"typecheck": "tsc --noEmit"},
        "devDependencies": {"typescript": "^5.6.0"},
    }
    return json.dumps(data, indent=2) + "\n"


def _tsconfig() -> str:
    data = {
        "compilerOptions": {
            "target": "ES2022",
            "module": "NodeNext",
            "moduleResolution": "NodeNext",
            "strict": True,
            "allowImportingTsExtensions": True,
            "noEmit": True,
            "verbatimModuleSyntax": True,
            "lib": ["ES2022", "DOM"],
        },
        "include": ["src"],
    }
    return json.dumps(data, indent=2) + "\n"
